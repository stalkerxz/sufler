import { chromium } from 'playwright';
import assert from 'node:assert/strict';
const browser=await chromium.launch({headless:true,channel:process.env.SUFLER_BROWSER_CHANNEL || undefined});
const context=await browser.newContext({viewport:{width:1440,height:1000}});
const page=await context.newPage(),errors=[];
page.on('pageerror',e=>errors.push(e.message));
page.on('console',m=>{if(m.type()==='error')errors.push(m.text())});
try {
await page.goto(process.env.SUFLER_TEST_URL || 'http://127.0.0.1:8765/');
await page.waitForSelector('.word');
assert.match(await page.title(),/Суфлёр/);
console.log('Loaded',await page.locator('.word').count(),'words');
await page.locator('#script-editor').fill('[улыбнуться] У нас 45 человек.\n\nВторой абзац для повторного дубля.\n\nТретий абзац завершает рассказ.');
await page.waitForTimeout(500);
assert.equal(await page.locator('.stage-direction').count(),1);
await page.locator('#speed-mode').click();
await page.selectOption('#countdown-seconds','0');
await page.locator('#start-button').click();
await page.waitForTimeout(700);
assert.equal(await page.locator('#start-button').getAttribute('aria-pressed'),'true');
await page.locator('#start-button').click();
await page.locator('#next-paragraph').click();
assert.equal(await page.locator('.word.current').innerText(),'Второй');
await page.selectOption('#countdown-seconds','3');
await page.locator('#retake-button').click();
assert.equal(await page.locator('#countdown-overlay').innerText(),'3');
await page.locator('#start-button').click();
assert.equal(await page.locator('#countdown-overlay').isVisible(),false);
await page.waitForTimeout(3200);
assert.equal(await page.locator('#start-button').getAttribute('aria-pressed'),'false');
console.log('Reading, paragraphs, countdown cancellation passed');
await page.locator('.library summary').click();
await page.locator('#script-title').fill('Сценарий проверки');
await page.waitForTimeout(350);
await page.locator('#script-copy').click();
assert.match(await page.locator('#script-title').inputValue(),/копия/);
await page.locator('#script-archive').click();
assert.equal(await page.locator('#script-title').inputValue(),'Сценарий проверки');
await page.locator('#script-recover').click();
assert.equal(await page.locator('#library-list option').count(),2);
await page.locator('#script-editor').fill('Ошибочная замена'); await page.waitForTimeout(400);
await page.locator('#revision-list').selectOption({index:0});
await page.locator('#revision-restore').click();
assert.notEqual(await page.locator('#script-editor').inputValue(),'Ошибочная замена');
const restoredTitle=await page.locator('#script-title').inputValue();
await page.reload(); await page.waitForSelector('.word');
assert.equal(await page.locator('#script-title').inputValue(),restoredTitle);
console.log('Library copy, archive, recover, revision and reload passed');
await page.locator('#view-tab').click();
await page.selectOption('#view-preset','camera');
assert.equal(await page.locator('#reading-position').inputValue(),'15');
await page.locator('#save-view-preset').click();
await page.selectOption('#view-preset','center');
await page.selectOption('#view-preset','custom');
assert.equal(await page.locator('#reading-position').inputValue(),'15');
const guide=page.locator('.reading-guide');
await guide.focus(); await page.keyboard.press('ArrowDown');
assert.equal(await page.locator('#reading-position').inputValue(),'16');
const b=await guide.boundingBox(), stage=await page.locator('#reader-stage').boundingBox();
await page.mouse.move(b.x+b.width/2,b.y+b.height/2);await page.mouse.down();await page.mouse.move(b.x+b.width/2,stage.y+stage.height*.65);await page.mouse.up();
assert.ok(Number(await page.locator('#reading-position').inputValue())>=63);
await page.locator('#dismiss-message').click();

await page.locator('#shoot-button').click();
assert.equal(await page.locator('.app-header').isVisible(),false);
await page.keyboard.press('Escape');
assert.equal(await page.locator('.app-header').isVisible(),true);
console.log('Presets, drag, keyboard marker, shooting passed');
if (process.env.SUFLER_TEST_REMOTE === '1') {
await page.locator('.remote-settings summary').click();
await page.locator('#remote-enable').click();
await page.waitForSelector('#remote-links a');
const remoteURL=await page.locator('#remote-links a').first().getAttribute('href');
const remoteContext=await browser.newContext({viewport:{width:390,height:844}});
const remote=await remoteContext.newPage();remote.on('pageerror',e=>errors.push('remote '+e.message));
await remote.goto(remoteURL);
await remote.waitForFunction(()=>!document.querySelector('[data-action="start"]').disabled);
await page.selectOption('#countdown-seconds','0');
await remote.locator('[data-action="start"]').click();
await page.waitForFunction(()=>document.getElementById('start-button').getAttribute('aria-pressed')==='true');
await remote.locator('[data-action="pause"]').click();
await page.waitForFunction(()=>document.getElementById('start-button').getAttribute('aria-pressed')==='false');

await page.locator('#remote-disable').click();
await page.waitForFunction(()=>document.getElementById('remote-status').textContent==='Пульт отключён.');
await remoteContext.close();
console.log('Remote separate browser context start/pause/disconnect passed');
}
await page.setViewportSize({width:390,height:844});
await page.locator('#reader-stage').focus();
assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
await page.locator('#toggle-sidebar').click();
await page.locator('#text-tab').click();
assert.equal(await page.locator('#script-editor').isVisible(),true);
await page.locator('#close-sidebar').click();
console.log('Mobile drawer and horizontal overflow passed');
assert.deepEqual(errors,[]);console.log('Console clean');
} finally { await browser.close(); }
